    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
    double LogaritmoNeperiano;
    double RaizCuadrada;
    String entrada = String.valueOf(txtValor.getText());
    double valor;
        
    if (entrada != null && ! entrada.trim().isEmpty()) {
        try {
            valor = Double.parseDouble(entrada);
            if (valor <= 0) {
                JOptionPane.showMessageDialog(this, "El valor debe ser mayor que cero para calcular el logaritmo", "Error de formato", JOptionPane.ERROR_MESSAGE);
            }
            txtLogaritmoNeperiano.setText(String.valueOf(CálculosNuméricos.calcularLogaritmoNeperiano(valor)));
            txtRaizCuadrada.setText(String.valueOf(CálculosNuméricos.calcularRaízCuadrada(valor)));
            } 
                catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "El valor ingresado debe ser numérico", "Error de formato", JOptionPane.ERROR_MESSAGE);
            }
     
    }
    

    else
        JOptionPane.showMessageDialog(this, "Debe ingresar un valor", "Error", JOptionPane.INFORMATION_MESSAGE);
    
        
    
   
    }//GEN-LAST:event_btnCalcularActionPerformed

