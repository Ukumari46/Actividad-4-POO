        String Universidad;
        String LP;
        String Nombre;
        String Apellidos;
        String entradaEquipo = String.valueOf(txtEquipo.getText());
        String entradaUniversidad = String.valueOf(txtUniversidad.getText());
        String entradaLP = String. valueOf(txtLP.getText());
        String entradaNombre = String.valueOf(txtNomInt.getText());
        String entradaApellidos = String.valueOf(txtApeInt.getText());
