    private void btnValidarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnValidarActionPerformed
        String entradaNombre = String.valueOf(txtNombre.getText());
        String entradaApellidos = String.valueOf(txtApellidos.getText());
        String entradaEdad = String.valueOf(txtEdad.getText());
        String nombre = entradaNombre;
        String apellidos = entradaApellidos;
        String edadString = entradaEdad;
        
        
        
        
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo Nombre no puede estar vacío.", "Error de validación", JOptionPane.WARNING_MESSAGE);
            txtNombre.requestFocus();
        
        
        
        }
        else if (apellidos.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo Apellidos no puede estar vacío.", "Error de validación", JOptionPane.WARNING_MESSAGE);
            txtApellidos.requestFocus();
        }
        
        else if (edadString.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo Edad no puede estar vacío.", "Error de validación", JOptionPane.WARNING_MESSAGE);
            txtEdad.requestFocus();
        
        
        
        }
        int edad = Integer.parseInt(entradaEdad);
        Vendedor.verificarEdad(edad);
    }//GEN-LAST:event_btnValidarActionPerformed

